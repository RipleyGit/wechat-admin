import http from './http'

export const api = {
  captcha: (uuid) => `${import.meta.env.VITE_API_ORIGIN || '/wx'}/captcha?uuid=${uuid}`,
  login: (data) => http.post('/sys/login', data),
  logout: () => http.post('/sys/logout'),
  me: () => http.get('/sys/user/info'),
  accounts: () => http.get('/manage/console/accounts'),
  context: () => http.get('/manage/console/context'),
  accountConfig: (appid) => http.get(`/manage/console/account-config/${appid}`),
  saveAccountConfig: (data) => http.post('/manage/console/account-config', data),
  notifySecret: (appid) => http.get(`/manage/console/account-config/${appid}/notify-secret`),
  regenerateNotifySecret: (appid) => http.post(`/manage/console/account-config/${appid}/notify-secret`),
  followers: (params) => http.get('/manage/wxUser/list', { params }),
  syncFollowers: () => http.post('/manage/wxUser/syncWxUsers'),
  setFollowerRemark: (data) => http.post('/manage/wxUser/updateRemark', data),
  tags: () => http.get('/manage/wxUserTags/list'),
  saveTag: (data) => http.post('/manage/wxUserTags/save', data),
  deleteTag: (id) => http.post(`/manage/wxUserTags/delete/${id}`),
  batchTag: (data) => http.post('/manage/wxUserTags/batchTagging', data),
  batchUnTag: (data) => http.post('/manage/wxUserTags/batchUnTagging', data),
  materials: (params) => http.get('/manage/wxAssets/materialFileBatchGet', { params }),
  materialCount: () => http.get('/manage/wxAssets/materialCount'),
  uploadMaterial: (data) => http.post('/manage/wxAssets/materialFileUpload', data),
  deleteMaterial: (data) => http.post('/manage/wxAssets/materialDelete', data),
  menu: () => http.get('/manage/wxMenu/getMenu'),
  saveMenu: (data) => http.post('/manage/wxMenu/updateMenu', data),
  rules: (params) => http.get('/manage/msgReplyRule/list', { params }),
  saveRule: (data) => http.post('/manage/msgReplyRule/save', data),
  updateRule: (data) => http.post('/manage/msgReplyRule/update', data),
  deleteRules: (ids) => http.post('/manage/msgReplyRule/delete', ids),
  qrcodes: (params) => http.get('/manage/wxQrCode/list', { params }),
  createQrcode: (data) => http.post('/manage/wxQrCode/createTicket', data),
  deleteQrcodes: (ids) => http.post('/manage/wxQrCode/delete', ids),
  msgSessions: (params) => http.get('/manage/wxMsg/sessions', { params }),
  msgTimeline: (params) => http.get('/manage/wxMsg/timeline', { params }),
  msgMarkRead: (data) => http.post('/manage/wxMsg/read', data),
  msgUnreadCount: () => http.get('/manage/wxMsg/unread-count'),
  sendMsg: (data) => http.post('/manage/wxMsg/send', data),
  notifyChannels: (params) => http.get('/manage/notifyChannel/list', { params }),
  saveNotifyChannel: (data) => http.post('/manage/notifyChannel/save', data),
  updateNotifyChannel: (data) => http.post('/manage/notifyChannel/update', data),
  deleteNotifyChannels: (ids) => http.post('/manage/notifyChannel/delete', ids),
  previewNotify: (data) => http.post('/manage/notifyChannel/preview', data),
  sendNotify: (data) => http.post('/manage/notifyChannel/send', data),
  notifyLogs: (params) => http.get('/manage/notifyChannel/logs', { params }),
  // 通道模板二维码：token 换成公开页 /channel-info/{token} 的内容
  channelQrcode: (id) => http.get(`/manage/notifyChannel/${id}/qrcode`),
  channelInfo: (token) => http.get(`/channel-info/${token}`, { silent: true }),
  msgTemplates: (params) => http.get('/manage/msgTemplate/list', { params }),
  syncMsgTemplates: () => http.post('/manage/msgTemplate/syncWxTemplate'),
  // 用户应用管理（sys_client_user_auth）。一行一条授权记录（用户 × 应用）。
  // update 是 PUT、delete 是 DELETE，和上面清一色 POST 不同，这是后端
  // SysClientUserAuthManageController 的写法，别照着改成 post
  clientUserAuths: (params) => http.get('/manage/sysClientUserAuth/list', { params }),
  saveClientUserAuth: (data) => http.post('/manage/sysClientUserAuth/save', data),
  updateClientUserAuth: (data) => http.put('/manage/sysClientUserAuth/update', data),
  deleteClientUserAuths: (ids) => http.delete('/manage/sysClientUserAuth/delete', { data: ids }),
}
